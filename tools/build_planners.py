# -*- coding: utf-8 -*-
"""Generate planner.html and assets/planners.js.

    python tools/build_planners.py

A planner card used to open a dialog. It opens a page now, which is what a
profile with a portfolio, a client list and a paid consultation flow on it
needs: a URL you can send someone, a back button that works, and room.

One page serving twenty four profiles, not twenty four pages. The page reads
?p=<slug> and renders from assets/planners.js, which is this script's other
output and is shaped exactly like the response /public/planners/{slug} has to
return. When that endpoint is live, planners.js is deleted and the same
renderer is pointed at a fetch; nothing else moves.

The consultation form on the page is the one the planner configures in the app:
the same four sections, the same field types, the planner's own welcome message
and rules of engagement, and their own consultation fee where they charge one.
"""
import io, os, sys, json

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from pagekit import head, FOOTER, write, V
from plannerdata import profiles

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

PS = profiles()

# A compact file, not a pretty one: it ships to every visitor of the page.
data = ("/* Generated by tools/build_planners.py. Do not edit.\n"
        "   Twenty four invented planner profiles, in the shape\n"
        "   GET /api/v1/public/planners/{slug} has to return. Replacing this file\n"
        "   with that fetch is the whole of the work when the endpoint is live. */\n"
        "window.EP_PLANNERS = "
        + json.dumps(PS, separators=(",", ":"), ensure_ascii=False) + ";\n")
io.open(os.path.join(ROOT, "assets/planners.js"), "w", encoding="utf-8", newline="\n").write(data)
print("  %-20s %6d bytes  %d profiles" % ("assets/planners.js", len(data), len(PS)))


# The page is a shell. Everything inside [data-planner] is written by
# assets/app.js from the profile it finds, because one markup skeleton for
# twenty four profiles is the point of doing it this way.
p = head("Planner | EventPlanna",
         "An approved EventPlanna planner: past events, portfolio, what they take on, and a "
         "consultation you can book in the same page.",
         "marketplace.html")

p += """
  <div data-planner data-v="%s">""" % V + """
    <section class="section" style="padding-top:clamp(96px,12vw,150px)">
      <div class="plp-miss">
        <h1>No planner named</h1>
        <p>This page needs a planner to show. Open one from the directory and it will load here.</p>
        <div class="hero-actions" style="justify-content:center">
          <a class="btn btn-dark" href="marketplace.html#directory">Back to the directory <span class="cap">&#8599;</span></a>
        </div>
      </div>
    </section>
  </div>
"""

# planners.js has to be parsed before app.js runs, because app.js reads the
# profile at evaluation time rather than waiting for an event.
tail = FOOTER.replace('<script src="assets/app.js',
                      '<script src="assets/planners.js?v=%s"></script>\n<script src="assets/app.js' % V)
write("planner.html", p + tail)
